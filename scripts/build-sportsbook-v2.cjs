#!/usr/bin/env node
/* SPORTSBOOK_V2_20260903
 * Builds the isolated preview route  sportsbook/v2/index.html  from the
 * PRODUCTION page  sportsbook/index.html  without touching production.
 *
 * The preview is byte-for-byte the live page plus:
 *   - <link>   /static/css/sportsbook-v2.css   (inert unless html.tmr-sbv2)
 *   - <script> /static/js/sportsbook-v2.js     (feature-flagged skin)
 *   - window.__TMR_SBV2_FORCE = true           (preview always renders v2)
 *   - <link rel=canonical> -> /sportsbook/     (preview never competes in SEO;
 *                                               never noindex per house rule)
 * Same backend, same submission logic, same DOM ids. Re-run after any
 * production sportsbook change:  node scripts/build-sportsbook-v2.cjs
 */
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const src = path.join(root, 'sportsbook', 'index.html');
const outDir = path.join(root, 'sportsbook', 'v2');
const out = path.join(outDir, 'index.html');
let html = fs.readFileSync(src, 'utf8');

const HEAD_INJECT =
  '\n    <!-- SPORTSBOOK_V2_20260903 preview route: generated by scripts/build-sportsbook-v2.cjs, do not hand edit -->\n' +
  '    <link rel="canonical" href="https://trustmyrecord.com/sportsbook/">\n' +
  '    <script>window.__TMR_SBV2_FORCE = true;</script>\n' +
  '    <link rel="stylesheet" href="/static/css/sportsbook-v2.css">\n' +
  '    <script src="/static/js/sportsbook-v2.js"></script>\n';

// Drop the production canonical so the preview carries exactly one.
html = html.replace(/\n\s*<link rel="canonical"[^>]*>/i, '');
if (!/<\/head>/i.test(html)) throw new Error('no </head> in sportsbook/index.html');
html = html.replace(/<\/head>/i, HEAD_INJECT + '</head>');
// Title marker so tabs / tests can tell the routes apart.
html = html.replace(/<title>([^<]*)<\/title>/i, (m, t) => `<title>${t} (v2 preview)</title>`);

fs.mkdirSync(outDir, { recursive: true });
fs.writeFileSync(out, html);
console.log('built', path.relative(root, out), html.length, 'bytes');
