#!/usr/bin/env node
/**
 * Bake data/team-logos.json down to the college half of the shared TeamLogo map.
 *
 * The four pro leagues live in static/js/tmr-team-logo.js itself (30-ish rows
 * each, hand-checked). College is 900+ schools, so it is generated: slug ->
 * ESPN team id, plus the school's own name ("louisville") where that is not
 * ambiguous, so a pick that says "Louisville" and one that says "Louisville
 * Cardinals" both resolve. NCAAF wins the single id disagreement with NCAAB.
 *
 *   node scripts/build-team-logo-catalog.cjs
 * then re-stamp: node scripts/stamp-asset-refs.js static/js/tmr-team-logo-catalog.js
 */
const fs = require('fs');
const path = require('path');
const root = path.resolve(__dirname, '..');
const src = JSON.parse(fs.readFileSync(path.join(root, 'data/team-logos.json'), 'utf8')).sports;

const slugify = (v) => String(v == null ? '' : v).toLowerCase()
  .normalize('NFKD').replace(/[̀-ͯ]/g, '')
  .replace(/&/g, 'and').replace(/[^a-z0-9]+/g, '-').replace(/^-+|-+$/g, '');

const byName = {};
const locCount = {};
const locId = {};
// NCAAB first, NCAAF second: NCAAF then overwrites the one row they disagree on.
for (const league of ['ncaab', 'ncaaf']) {
  for (const t of (src[league] || {}).teams || []) {
    if (!t.id) continue;
    byName[slugify(t.display)] = String(t.id);
    const loc = slugify(t.location);
    if (loc) {
      if (locId[loc] !== String(t.id)) locCount[loc] = (locCount[loc] || 0) + 1;
      locId[loc] = String(t.id);
    }
  }
}
// A bare school name only counts when every league agrees which school it is.
for (const loc of Object.keys(locId)) {
  if (locCount[loc] === 1 && !byName[loc]) byName[loc] = locId[loc];
}
const keys = Object.keys(byName).sort();
const body = keys.map((k) => JSON.stringify(k) + ':' + JSON.stringify(byName[k])).join(',\n');
const out = `/* GENERATED by scripts/build-team-logo-catalog.cjs from data/team-logos.json.
 * Do not hand-edit. College team slug -> ESPN team id; the shared TeamLogo
 * helper turns that into https://a.espncdn.com/i/teamlogos/ncaa/500/<id>.png.
 * Loading this file is optional: without it college names fall back to the
 * standardised initials badge, exactly as before. */
window.TMRTeamLogoCatalog = {
${body}
};
`;
const dest = path.join(root, 'static/js/tmr-team-logo-catalog.js');
fs.writeFileSync(dest, out.replace(/\n/g, '\r\n'), 'utf8');
console.log('wrote', dest, keys.length, 'schools,', (out.length / 1024).toFixed(1), 'KB');
