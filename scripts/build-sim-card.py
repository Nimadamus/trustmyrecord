#!/usr/bin/env python3
"""FEED_SIM_CARD_20261114: build static/js/tmr-sim-card.js.

The simulation card is written once, in static/js/feed-v2.js (functions) and
static/css/feed-v2.css (styles). Pages that do not load the feed bundle (the
profile Takes list) get the same card from a standalone copy generated here, so
there is one source and tests/feed-sim-card-test.js fails if the copy is stale.

    python scripts/build-sim-card.py          write the file
    python scripts/build-sim-card.py --check  exit 1 if it is out of date
"""
import io
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SCOPE = 'body.feed-v2.tmr-site-shell.tmr-dark '
TOKENS = ("--fv-card-2:#0E1B36;--fv-inset:#081022;--fv-line:rgba(70,118,200,.34);--fv-line-soft:rgba(110,145,205,.16);"
          "--fv-blue:#2B8CFF;--fv-blue-2:#0F5FE0;--fv-cyan:#63C3FF;--fv-green:#2EE37B;--fv-red:#FF4D5E;"
          "--fv-text:#F3F7FD;--fv-text-2:#C3CFE2;--fv-muted:#8C9BB5;"
          "--fv-display:'Barlow Condensed','Barlow','Inter',sans-serif")


def read(rel):
    return io.open(os.path.join(ROOT, rel), encoding='utf-8', newline='').read().replace('\r\n', '\n')


def build():
    js = read('static/js/feed-v2.js')
    a, b = js.index('function fvSimNum'), js.index('function renderTextPost')
    funcs = js[a:b].rstrip() + '\n'
    css = read('static/css/feed-v2.css')
    c = css.index('/* FEED_SIM_CARD_20261114')
    block = css[c:]
    block = block[block.index('*/') + 2:]
    rules = []
    for line in block.split('\n'):
        line = line.strip()
        if line:
            rules.append(line.replace(SCOPE, '.tsc-host '))
    style = '.tsc-host{' + TOKENS + ';text-align:left}.tsc-host *{box-sizing:border-box}' + ''.join(rules) \
        + '.tsc-host .fv-sim{margin-left:0}'
    out = [
        '/* GENERATED by scripts/build-sim-card.py from static/js/feed-v2.js and',
        '   static/css/feed-v2.css. Do not edit: change those and rebuild.',
        '   FEED_SIM_CARD_20261114: the simulation card for pages without the feed bundle.',
        '   window.TMRSimCard.node(item) -> a ready element, or null when the post has no simulation. */',
        '(function (window, document) {',
        "'use strict';",
        'if (window.TMRSimCard) return;',
        'function esc(s) {',
        "    return String(s == null ? '' : s).replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;').replace(/\"/g, '&quot;').replace(/'/g, '&#39;');",
        '}',
        "function getDisplayName(item) { return item.display_name || item.username || 'Member'; }",
        funcs,
        'var CSS = ' + repr_js(style) + ';',
        'function node(item) {',
        '    var html = item ? fvSimCard(item) : \'\';',
        '    if (!html) return null;',
        "    if (!document.getElementById('tmr-sim-card-css')) {",
        "        var s = document.createElement('style');",
        "        s.id = 'tmr-sim-card-css';",
        '        s.textContent = CSS;',
        '        document.head.appendChild(s);',
        '    }',
        "    var host = document.createElement('div');",
        "    host.className = 'tsc-host';",
        '    host.innerHTML = html;',
        '    return host;',
        '}',
        'window.TMRSimCard = { node: node, html: fvSimCard };',
        '})(window, document);',
        '',
    ]
    return '\n'.join(out)


def repr_js(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    target = os.path.join(ROOT, 'static/js/tmr-sim-card.js')
    want = build()
    if '--check' in sys.argv:
        have = io.open(target, encoding='utf-8', newline='').read().replace('\r\n', '\n') if os.path.exists(target) else ''
        if have != want:
            print('static/js/tmr-sim-card.js is out of date: run python scripts/build-sim-card.py')
            sys.exit(1)
        print('tmr-sim-card.js is current')
        return
    io.open(target, 'w', encoding='utf-8', newline='\n').write(want)
    print('wrote static/js/tmr-sim-card.js')


if __name__ == '__main__':
    main()
